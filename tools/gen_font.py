#!/usr/bin/env python3
"""Generate the kernel's 8x16 bitmap font from DejaVu Sans Mono.

DejaVu fonts are distributed under a permissive (Bitstream Vera derived)
licence; only the rasterised ASCII subset is embedded in the kernel.

Usage:
    python tools/gen_font.py [--font PATH] [--preview OUT.png]

The output is deterministic so builds on different machines produce the
same kernel/font/font8x16.c bytes.
"""

import argparse
import os
import struct
import sys

CELL_W, CELL_H = 8, 16
FIRST, LAST = 32, 126


def find_default_font() -> str:
    candidates = [
        os.path.join(os.path.dirname(__file__), "..", "assets", "fonts", "DejaVuSansMono.ttf"),
    ]
    try:
        import matplotlib
        candidates.append(os.path.join(os.path.dirname(matplotlib.__file__),
                                       "mpl-data", "fonts", "ttf", "DejaVuSansMono.ttf"))
    except Exception:
        pass
    candidates += [
        "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
        r"C:\Windows\Fonts\consola.ttf",
    ]
    for path in candidates:
        if path and os.path.exists(path):
            return os.path.abspath(path)
    raise SystemExit("no usable font found; pass --font PATH")


def render(font_path: str):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(font_path, 13)
    glyphs = []
    atlas = Image.new("L", (CELL_W * 16, CELL_H * 8), 0)
    adraw = ImageDraw.Draw(atlas)

    for code in range(256):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        if FIRST <= code <= LAST:
            ch = chr(code)
            draw = ImageDraw.Draw(img)
            if hasattr(draw, "textbbox"):
                l, t, r, b = draw.textbbox((0, 0), ch, font=font)
            else:  # Pillow < 8.0
                w, h = draw.textsize(ch, font=font)
                l, t, r, b = 0, 0, w, h
            x = (CELL_W - (r - l)) // 2 - l
            y = (CELL_H - (b - t)) // 2 - t
            draw.text((x, y), ch, font=font, fill=255)
        rows = []
        for y in range(CELL_H):
            bits = 0
            for x in range(CELL_W):
                if img.getpixel((x, y)) > 110:
                    bits |= 0x80 >> x
            rows.append(bits)
        glyphs.append(rows)
        if FIRST <= code <= LAST:
            atlas.paste(img, ((code - FIRST) % 16 * CELL_W, (code - FIRST) // 16 * CELL_H))
    return glyphs, atlas


def write_c(glyphs, out_path: str):
    lines = [
        "/* Auto-generated by tools/gen_font.py -- do not edit by hand.",
        " * Source: DejaVu Sans Mono 13px cell 8x16.",
        " * Encoding: 256 glyphs x 16 rows, MSB = leftmost pixel. */",
        "",
        "#include <mcube/types.h>",
        "",
        "const u8 mc_font8x16[256][16] = {",
    ]
    for code, rows in enumerate(glyphs):
        comment = chr(code) if FIRST <= code <= LAST and chr(code) not in "\\\"'*/" else ""
        if comment:
            label = f" /* '{comment}' */"
        else:
            label = ""
        lines.append("    {" + ", ".join(f"0x{b:02X}" for b in rows) + "}," + label)
    lines.append("};")
    lines.append("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {out_path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..",
                                                  "kernel", "font", "font8x16.c"))
    ap.add_argument("--preview", default=None)
    args = ap.parse_args()

    font_path = args.font or find_default_font()
    print(f"font: {font_path}")
    glyphs, atlas = render(font_path)
    write_c(glyphs, os.path.abspath(args.out))
    if args.preview:
        atlas.resize((CELL_W * 16 * 3, CELL_H * 8 * 3), 0).save(args.preview)
        print(f"preview: {args.preview}")


if __name__ == "__main__":
    main()
