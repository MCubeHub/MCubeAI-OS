#!/usr/bin/env python3
"""Embed a binary file as a C array (used for the init ELF)."""

import sys


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: gen_blob.py <symbol> <input> <output>", file=sys.stderr)
        return 2

    symbol, src, dst = sys.argv[1:4]
    data = open(src, "rb").read()

    with open(dst, "w", encoding="ascii") as f:
        f.write("/* generated by tools/gen_blob.py -- do not edit */\n")
        f.write("#include <mcube/types.h>\n\n")
        f.write(f"const u8 {symbol}[] = {{\n")
        for i in range(0, len(data), 16):
            chunk = ",".join(f"0x{b:02x}" for b in data[i:i + 16])
            f.write(f"    {chunk},\n")
        f.write("};\n\n")
        f.write(f"const u64 {symbol}_size = {len(data)}ULL;\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
