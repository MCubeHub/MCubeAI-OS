#!/usr/bin/env python3
"""Generate the desktop's anti-aliased 8x16 UI font.

The kernel console font (tools/gen_font.py) is 1 bpp: every glyph pixel is
either on or off, which is fine for a serial console but leaves 1 px ragged
stems on a 1920x1200 desktop. This generator renders the same Cells from
DejaVu Sans Mono as **8-bit coverage** masks, so the shell can composite text
with proper anti-aliasing, and emits a second bold table for headings,
window titles and the taskbar so the interface has a real type hierarchy.

Usage:
    python3 tools/gen_ui_font.py [--px 13] [--preview OUT.png]
"""

import argparse
import os

CELL_W, CELL_H = 8, 16
FIRST, LAST = 32, 126


def find_font(name: str) -> str:
    candidates = [
        os.path.join(os.path.dirname(__file__), "..", "assets", "fonts", name),
        os.path.join("/usr/share/fonts/truetype/dejavu", name),
    ]
    try:
        import matplotlib
        candidates.append(os.path.join(matplotlib.__file__, "..", "mpl-data",
                                       "fonts", "ttf", name))
    except Exception:
        pass
    candidates.append(os.path.join("C:\\Windows\\Fonts", name))
    for path in candidates:
        path = os.path.normpath(path)
        if os.path.exists(path):
            return path
    raise SystemExit(f"cannot find {name}; install fonts-dejavu-core")


def render(font_path: str, px: int):
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(font_path, px)
    glyphs = []
    for code in range(256):
        img = Image.new("L", (CELL_W, CELL_H), 0)
        if FIRST <= code <= LAST:
            ch = chr(code)
            draw = ImageDraw.Draw(img)
            if hasattr(draw, "textbbox"):
                l, t, r, b = draw.textbbox((0, 0), ch, font=font)
            else:
                w, h = draw.textsize(ch, font=font)
                l, t, r, b = 0, 0, w, h
            x = (CELL_W - (r - l)) // 2 - l
            y = (CELL_H - (b - t)) // 2 - t
            draw.text((x, y), ch, font=font, fill=255)
        glyphs.append([img.getpixel((x, y)) for y in range(CELL_H)
                       for x in range(CELL_W)])
    return glyphs


def emit_table(name: str, glyphs) -> str:
    out = [f"const u8 {name}[256][{CELL_W * CELL_H}] = {{"]
    for code, cov in enumerate(glyphs):
        label = ""
        if FIRST <= code <= LAST and chr(code) not in "\\\"'*/":
            label = f" /* '{chr(code)}' */"
        out.append("    {" + ", ".join(f"{v:3d}" for v in cov) + "}," + label)
    out.append("};")
    return "\n".join(out)


def write_c(reg, bold, out_path: str):
    text = [
        "/* Auto-generated by tools/gen_ui_font.py -- do not edit by hand.",
        " * Source: DejaVu Sans Mono, 8-bit coverage per pixel, cell 8x16.",
        " * Row-major: 16 rows of 8 columns, 0 = background, 255 = full ink. */",
        "",
        "#include <mcube/types.h>",
        "",
        emit_table("mc_ui_font", reg),
        "",
        emit_table("mc_ui_font_bold", bold),
        "",
    ]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(text))
    print(f"wrote {out_path}")


SAMPLES = [
    ("regular", "MCubeAIOS Settings 0123"),
    ("bold", "MCubeAIOS Settings 0123"),
]


def preview(reg, bold, px: int, out_path: str):
    from PIL import Image, ImageDraw

    rows = [("regular", reg), ("bold", bold)]
    line_h = 20
    pad = 6
    width = 8 * 26 + 2 * pad
    height = len(rows) * (line_h + 4) + pad
    img = Image.new("RGB", (width, height), (12, 18, 27))
    draw = ImageDraw.Draw(img)
    y = pad
    for name, glyphs in rows:
        x = pad
        for ch in SAMPLES[0][1]:
            cov = glyphs[ord(ch)]
            for gy in range(CELL_H):
                for gx in range(CELL_W):
                    a = cov[gy * 8 + gx]
                    if not a:
                        continue
                    fg = (232, 236, 244)
                    bg = img.getpixel((x + gx, y + gy))
                    px_c = tuple(bg[i] + (fg[i] - bg[i]) * a // 255 for i in range(3))
                    draw.point((x + gx, y + gy), px_c)
            x += CELL_W
        y += line_h
    img.resize((width * 3, height * 3), Image.NEAREST).save(out_path)
    print(f"preview: {out_path} ({px}px)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--px", type=int, default=13)
    ap.add_argument("--preview")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..",
                                                  "kernel", "font", "ui_font.c"))
    args = ap.parse_args()

    reg_path = find_font("DejaVuSansMono.ttf")
    bold_path = find_font("DejaVuSansMono-Bold.ttf")
    print(f"regular: {reg_path}")
    print(f"bold   : {bold_path}")

    reg = render(reg_path, args.px)
    bold = render(bold_path, args.px)

    if args.preview:
        preview(reg, bold, args.px, args.preview)
    else:
        write_c(reg, bold, os.path.abspath(args.out))


if __name__ == "__main__":
    main()
